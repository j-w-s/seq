local Seq = require("seq")

describe("seq", function()
  it("loads correctly", function()
    assert.is_not_nil(Seq)
    assert.is_same(type(Seq), "table")
  end)

  it("has source methods attached", function()
    assert.equal("function", type(Seq.from))
    assert.equal("function", type(Seq.from_pairs))
    assert.equal("function", type(Seq.range))
    assert.equal("function", type(Seq.repeat_))
  end)

  it("has single-value combinator methods attached", function()
    assert.equal("function", type(Seq.map))
    assert.equal("function", type(Seq.filter))
    assert.equal("function", type(Seq.take))
    assert.equal("function", type(Seq.take_while))
    assert.equal("function", type(Seq.drop))
    assert.equal("function", type(Seq.drop_while))
    assert.equal("function", type(Seq.scan))
    assert.equal("function", type(Seq.chain))
    assert.equal("function", type(Seq.enumerate))
    assert.equal("function", type(Seq.zip))
    assert.equal("function", type(Seq.flat_map))
  end)

  it("has key/value combinator pair methods attached", function()
    assert.equal("function", type(Seq.map2))
    assert.equal("function", type(Seq.filter2))
    assert.equal("function", type(Seq.scan2))
    assert.equal("function", type(Seq.chain2))
    assert.equal("function", type(Seq.values))
    assert.equal("function", type(Seq.keys))
  end)

  it("has terminal methods attached", function()
    assert.equal("function", type(Seq.collect))
    assert.equal("function", type(Seq.collect2))
    assert.equal("function", type(Seq.collect_pairs))
    assert.equal("function", type(Seq.reduce))
    assert.equal("function", type(Seq.each))
    assert.equal("function", type(Seq.length))
    assert.equal("function", type(Seq.find))
    assert.equal("function", type(Seq.any))
    assert.equal("function", type(Seq.all))
  end)
end)